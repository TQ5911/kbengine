CREATE TABLE IF NOT EXISTS lease_market (
	id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT COMMENT '自增主键',
	unique_id BIGINT UNSIGNED NOT NULL DEFAULT 0 COMMENT '装备全局唯一 ID，跨服唯一标识',
	item_id INT UNSIGNED NOT NULL DEFAULT 0 COMMENT '装备配置 ID',
	return_owner_gbid BIGINT UNSIGNED NOT NULL DEFAULT 0 COMMENT '链条顶端原出租方/最终归还方 gbId',
	return_owner_server_id INT UNSIGNED NOT NULL DEFAULT 0 COMMENT '链条顶端原出租方/最终归还方所在服 ID',
	return_time INT UNSIGNED NOT NULL DEFAULT 0 COMMENT '归还时间/到期时间，正常租赁或爆装归还时使用',
	return_reason TINYINT UNSIGNED NOT NULL DEFAULT 0 COMMENT '归还原因 0=未设置/不退回 1=爆装 2=租赁',
	lease_days INT UNSIGNED NOT NULL DEFAULT 0 COMMENT '租赁天数',
	lessor_gbid BIGINT UNSIGNED NOT NULL DEFAULT 0 COMMENT '当前出租方 gbId（本次上架/出租方）',
	lessor_server_id INT UNSIGNED NOT NULL DEFAULT 0 COMMENT '当前出租方所在服 ID',
	lessee_gbid BIGINT UNSIGNED NOT NULL DEFAULT 0 COMMENT '当前承租方 gbId',
	lessee_server_id INT UNSIGNED NOT NULL DEFAULT 0 COMMENT '当前承租方所在服 ID',
	price_per_day BIGINT NOT NULL DEFAULT 0 COMMENT '每日租金',
	lease_start_time INT UNSIGNED NOT NULL DEFAULT 0 COMMENT '本次租赁开始时间',
	lease_end_time INT UNSIGNED NOT NULL DEFAULT 0 COMMENT '本次租赁结束时间，对应实际截止归还时间',
	lease_cost BIGINT NOT NULL DEFAULT 0 COMMENT '承租方花费租金',
	lease_gold BIGINT NOT NULL DEFAULT 0 COMMENT '出租方获得流通金',
	lease_bind_gold BIGINT NOT NULL DEFAULT 0 COMMENT '出租方获得绑定金',
	lease_tax BIGINT NOT NULL DEFAULT 0 COMMENT '平台税金（从租金中扣除）',
	item_data MEDIUMTEXT NOT NULL COMMENT '装备序列化 JSON 数据，包含租赁状态和属性',
	lease_status TINYINT UNSIGNED NOT NULL DEFAULT 1 COMMENT '订单状态 1=预上架 2=上架中 3=已租出 4=已下架 5=预锁定 6=已过期',
	create_time INT UNSIGNED NOT NULL DEFAULT 0 COMMENT '记录创建时间',
	update_time INT UNSIGNED NOT NULL DEFAULT 0 COMMENT '记录更新时间',
	PRIMARY KEY (id),
	UNIQUE KEY uk_unique (unique_id),
	KEY idx_status_id (lease_status, id),
	KEY idx_status_updatetime (lease_status, update_time),
	KEY idx_status_leaseend (lease_status, lease_end_time)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='租赁市场全局订单表';
