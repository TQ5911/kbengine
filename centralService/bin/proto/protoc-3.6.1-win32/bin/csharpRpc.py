#!/usr/bin/python
import sys
import json
import itertools
from google.protobuf.compiler import plugin_pb2 as plugin
from google.protobuf.descriptor_pb2 import DescriptorProto, EnumDescriptorProto

def _(content, ni=1):
    linesep = '\n'
    indent = ' '*4
    lines = content.split(linesep)

    ret = ''
    for i, line in enumerate(lines):
        if i==len(lines)-1 and not line:
            break

        ret += indent*ni+line+linesep

    return ret

def strCapitalize(s):
    if not s:
        return ''
    return s[0].upper()+s[1:]

def generate_code(request, response):
    for protoFile in request.proto_file:
        body = 'using Proto;\n'
        body += 'using Google.Protobuf;\n\n'

        #generate rpc method from service
        for serviceDesc in protoFile.service:
            service = 'public class %sStub\n'%serviceDesc.name
            service += '{\n'
            service += _('public RpcChannel rpcChannel;')
            service += _('public %sStub(RpcChannel channel)\n'%serviceDesc.name)
            service += _('{\n')
            service += _('rpcChannel = channel;\n', ni=2)
            service += _('}\n\n')
            for methodIdx, methodDesc in enumerate(serviceDesc.method):
                argType = methodDesc.input_type.split('.')[-1]
                methodName = strCapitalize(methodDesc.name)
                method = 'public void %s(%s arg)\n'%(methodName, argType)
                method += '{\n'
                method += _('rpcChannel.callMethod(%s, arg.ToByteArray());'%methodIdx);
                method += '}\n\n'

                service += _(method)
            service+='}\n\n'

            service += 'public class %sBase:ServiceBase\n'%serviceDesc.name
            service += '{\n'


            switchStr = 'switch(methodIndex)\n'
            switchStr +='{\n'

            for methodIdx, methodDesc in enumerate(serviceDesc.method):
                argType = methodDesc.input_type.split('.')[-1]
                methodName = strCapitalize(methodDesc.name)
                methodDec = 'public virtual void %s(%s arg) {}\n'%(methodName, argType)

                service += _(methodDec)

                switchStr += _('case %s:\n'%methodIdx)
                switchStr += _('%s(%s.Parser.ParseFrom(data));'%(methodName, argType), ni=2)
                switchStr += _('break;', ni=2)

            switchStr += _('default:\n')
            switchStr += _('break;\n', ni=2)
            switchStr += _('}\n')


            handleFunc = 'public override void handleRpcRequest(int methodIndex, byte[] data)\n'
            handleFunc +='{\n'
            handleFunc +=_(switchStr)
            handleFunc += '}\n'

            service += _(handleFunc)
            service += '}\n\n'

            body += service

        content = '// Generated by protobuf plugin.  DO NOT EDIT!\n\n'
        if protoFile.package:
            content += 'namespace %s\n'%protoFile.package
            content += '{\n'
            content += _(body)
            content += '}'
        else:
            content += body

        # Fill response
        f = response.file.add()
        f.name = '%sService.cs'%protoFile.package
        f.content = content

if __name__ == '__main__':
    # Read request message from stdin
    data = sys.stdin.buffer.read()

    # Parse request
    request = plugin.CodeGeneratorRequest()
    request.ParseFromString(data)

    # Create response
    response = plugin.CodeGeneratorResponse()

    # Generate code
    generate_code(request, response)

    # Serialise response message
    output = response.SerializeToString()

    # Write to stdout
    sys.stdout.buffer.write(output)
