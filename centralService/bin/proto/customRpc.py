#!/usr/bin/python
import sys
import os
import json
import itertools
from google.protobuf.compiler import plugin_pb2 as plugin
from google.protobuf.descriptor_pb2 import DescriptorProto, EnumDescriptorProto

def _(content, ni=1):
    linesep = '\n'
    indent = ' '*4
    lines = content.split(linesep)

    ret = ''
    for i, line in enumerate(lines):
        if i==len(lines)-1 and not line:
            break

        ret += indent*ni+line+linesep

    return ret

def strCapitalize(s):
    if not s:
        return ''
    return s[0].upper()+s[1:]

def generate_code(request, response, rpcPackagePath):

    for protoFile in request.proto_file:
        if protoFile.name not in request.file_to_generate:
            continue

        pkgName = protoFile.package
        gopkg = getattr(protoFile.options, 'go_package', '')
        if gopkg:
            pkgName = os.path.basename(gopkg)

        body = 'package {}\n\n'.format(pkgName)
        body += 'import (\n'
        body += _('prpc "{}"\n'.format(rpcPackagePath))
        body += ')\n\n'

        #generate rpc method from service
        for serviceDesc in protoFile.service:
            srvName = serviceDesc.name
            service = ''

            methodList = ''
            methodDefs = ''
            interfaceMethods = ''
            for methodIdx, methodDesc in enumerate(serviceDesc.method):
                argType = strCapitalize(methodDesc.input_type.split('.')[-1])
                retType = strCapitalize(methodDesc.output_type.split('.')[-1])
                methodName = strCapitalize(methodDesc.name)
                service += 'func %s_%s_Handler(endPoint prpc.IEndPoint, dec func(interface{}) error) (interface{}, error) {\n' % (srvName, methodName)
                service += _('in := new(%s)'%argType)
                service += _('if err := dec(in); err != nil {')
                service += _('return nil, err', ni=2)
                service += _('}')
                service += _('return endPoint.(I%sInterface).%s(in)'%(srvName, methodName))
                service += '}\n'

                methodList += _('{')
                methodList += _('MethodName:  "%s",'%methodName, ni=2)
                methodList += _('MethodIndex: %s,'%methodIdx, ni=2)
                methodList += _('Handler:     %s_%s_Handler,'%(srvName, methodName), ni=2)
                methodList += _('},')

                methodDefs += 'func (self *%sClient) %s(in *%s) (*%s, error) {\n'%(srvName, methodName, argType, retType)
                methodDefs += _('err := self.Channel.CallMethod(&%sServiceDesc.Methods[%s], in)'%(srvName, methodIdx))
                methodDefs += _('return &%s{}, err'%retType)
                methodDefs += '}\n'

                interfaceMethods += _('%s(*%s) (*%s, error)'%(methodName, argType, retType))


            service += 'var %sServiceDesc = prpc.ServiceDesc{\n'%srvName
            service += _('ServiceName: "%s.%s",'%(protoFile.package, srvName))
            service += _('Methods: []prpc.MethodDesc{')
            service += _(methodList)
            service += _('},')
            service += '}\n\n'

            service += 'func New%sService(client prpc.IEndPoint) *prpc.ServerEndPoint {\n'%(srvName,)
            service += _('return &prpc.ServerEndPoint{&%sServiceDesc, client}'%srvName)
            service += '}\n\n'

            service += 'func New%sClient(channel *prpc.RpcChannel) *%sClient {\n' % (srvName, srvName)
            service += _('return &%sClient{prpc.ClientEndPoint{channel}}' % srvName)
            service += '}\n\n'

            service += '''type %sClient struct {
	prpc.ClientEndPoint
}\n'''%(srvName,)

            service += methodDefs

            service += 'type I%sInterface interface {\n' % (srvName,)
            service += interfaceMethods
            service += '}\n\n'

            body += service

        content = '// Generated by protobuf plugin.  DO NOT EDIT!\n\n'
        content += body

        # Fill response
        f = response.file.add()
        f.name = '/'.join([gopkg, '%s.rpc.go'%os.path.splitext(protoFile.name)[0]])
        f.content = content

if __name__ == '__main__':
    # Read request message from stdin
    data = sys.stdin.buffer.read()

    # Parse request
    request = plugin.CodeGeneratorRequest()
    request.ParseFromString(data)

    # Create response
    response = plugin.CodeGeneratorResponse()

    # Generate code
    rpcPackagePath = sys.argv[1]
    generate_code(request, response, rpcPackagePath)

    # Serialise response message
    output = response.SerializeToString()

    # Write to stdout
    sys.stdout.buffer.write(output)
