CREATE TABLE IF NOT EXISTS `orderData`
(
    id bigint unsigned AUTO_INCREMENT,
    `orderNo` varchar(64) not null DEFAULT '',
    `outTradeNo` varchar(64) not null DEFAULT '',
    `createTime` bigint not null DEFAULT 0,
    `gameId` varchar(32) not null DEFAULT '',
    `userGameId` varchar(300) not null DEFAULT '',
    `userId` bigint not null DEFAULT 0,
    `userRoleId` bigint not null DEFAULT 0,
    `roleName` varchar(64) not null DEFAULT '',
    `serverId` int unsigned not null DEFAULT 0,
    `serverName` varchar(64) not null DEFAULT '',
    `productId` varchar(64) not null DEFAULT '',
    `productCode` bigint not null DEFAULT 0,
    `channelProductId` varchar(64) not null DEFAULT '',
    `productName` varchar(128) not null DEFAULT '',
    `buyNum` int unsigned not null DEFAULT 0,
	`payTime` bigint not null DEFAULT 0,
    `payableAmount` decimal(16,2) not null DEFAULT 0.0,
    `actualAmount` decimal(16,2) not null DEFAULT 0.0,
    `payType` varchar(32) not null DEFAULT '',
    `orderSource` varchar(32) not null DEFAULT '',
    `orderProcessStatus` tinyint not null DEFAULT 0,
    `addToSafe` tinyint not null DEFAULT 0,
    UNIQUE INDEX (`orderNo`),
    UNIQUE INDEX (`outTradeNo`),
    PRIMARY KEY idKey (id)
);